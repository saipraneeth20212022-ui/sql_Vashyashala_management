-- ?????????????????????????????????????????????
-- ROW_NUMBER: Assign admission sequence per patient
-- ?????????????????????????????????????????????
SELECT
    a.PatientID,
    CONCAT(p.FirstName,' ',p.LastName) AS Patient,
    a.AdmissionDate,
    a.Diagnosis,
    ROW_NUMBER() OVER (
        PARTITION BY a.PatientID 
        ORDER BY a.AdmissionDate
    ) AS AdmissionNumber
FROM Admissions a
JOIN Patients p ON a.PatientID = p.PatientID;
GO

-- ?????????????????????????????????????????????
-- RANK vs DENSE_RANK: Doctor ranking by patient count
-- ?????????????????????????????????????????????
SELECT
    CONCAT(d.FirstName,' ',d.LastName) AS Doctor,
    d.Specialization,
    COUNT(a.AdmissionID)    AS PatientCount,
    RANK()       OVER (ORDER BY COUNT(a.AdmissionID) DESC) AS Rnk,
    DENSE_RANK() OVER (ORDER BY COUNT(a.AdmissionID) DESC) AS DenseRnk
FROM Doctors d
LEFT JOIN Admissions a ON d.DoctorID = a.DoctorID
GROUP BY d.DoctorID, d.FirstName, d.LastName, d.Specialization;
GO

-- ?????????????????????????????????????????????
-- NTILE: Quartile bucketing of patients by age
-- (Used for age-group risk stratification)
-- ?????????????????????????????????????????????
SELECT
    PatientID,
    CONCAT(FirstName,' ',LastName) AS Patient,
    Age,
    NTILE(4) OVER (ORDER BY Age) AS AgeQuartile,
    CASE NTILE(4) OVER (ORDER BY Age)
        WHEN 1 THEN 'Q1: Young (0-25%)'
        WHEN 2 THEN 'Q2: Middle-Young (25-50%)'
        WHEN 3 THEN 'Q3: Middle-Old (50-75%)'
        WHEN 4 THEN 'Q4: Senior (75-100%)'
    END AS AgeGroup
FROM Patients
WHERE Age IS NOT NULL;
GO

-- ?????????????????????????????????????????????
-- LAG / LEAD: Compare billing month-over-month
-- ?????????????????????????????????????????????
WITH MonthlyRevenue AS (
    SELECT
        FORMAT(b.BillDate, 'yyyy-MM') AS BillMonth,
        SUM(b.TotalAmount) AS Revenue
    FROM Billing b
    GROUP BY FORMAT(b.BillDate, 'yyyy-MM')
)
SELECT
    BillMonth,
    Revenue,
    LAG(Revenue,  1) OVER (ORDER BY BillMonth) AS PrevMonthRevenue,
    LEAD(Revenue, 1) OVER (ORDER BY BillMonth) AS NextMonthRevenue,
    Revenue - LAG(Revenue, 1) OVER (ORDER BY BillMonth) AS MoM_Change,
    CASE 
        WHEN LAG(Revenue,1) OVER (ORDER BY BillMonth) = 0 THEN NULL
        ELSE CAST(
            (Revenue - LAG(Revenue,1) OVER (ORDER BY BillMonth)) * 100.0 
            / LAG(Revenue,1) OVER (ORDER BY BillMonth) 
            AS DECIMAL(5,2))
    END AS MoM_Pct_Change
FROM MonthlyRevenue
ORDER BY BillMonth;
GO

-- ?????????????????????????????????????????????
-- Running Total: Cumulative revenue over time
-- ?????????????????????????????????????????????
SELECT
    b.BillID,
    FORMAT(b.BillDate,'yyyy-MM-dd') AS BillDate,
    b.TotalAmount,
    SUM(b.TotalAmount) OVER (
        ORDER BY b.BillDate 
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS CumulativeRevenue,
    AVG(CAST(b.TotalAmount AS FLOAT)) OVER (
        ORDER BY b.BillDate 
        ROWS BETWEEN 2 PRECEDING AND CURRENT ROW
    ) AS Rolling3BillAvg
FROM Billing b
ORDER BY b.BillDate;
GO

-- ?????????????????????????????????????????????
-- FIRST_VALUE / LAST_VALUE: First and latest 
-- diagnosis per patient
-- ?????????????????????????????????????????????
SELECT DISTINCT
    a.PatientID,
    CONCAT(p.FirstName,' ',p.LastName) AS Patient,
    FIRST_VALUE(a.Diagnosis) OVER (
        PARTITION BY a.PatientID 
        ORDER BY a.AdmissionDate 
        ROWS UNBOUNDED PRECEDING
    ) AS FirstDiagnosis,
    LAST_VALUE(a.Diagnosis) OVER (
        PARTITION BY a.PatientID 
        ORDER BY a.AdmissionDate 
        ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING
    ) AS LatestDiagnosis
FROM Admissions a
JOIN Patients p ON a.PatientID = p.PatientID;
GO

-- ?????????????????????????????????????????????
-- PERCENT_RANK: Where does each doctor's salary
-- rank within their department?
-- ?????????????????????????????????????????????
SELECT
    CONCAT(d.FirstName,' ',d.LastName) AS Doctor,
    dep.DeptName,
    d.Salary,
    ROUND(PERCENT_RANK() OVER (
        PARTITION BY d.DepartmentID 
        ORDER BY d.Salary
    ) * 100, 1) AS SalaryPercentile
FROM Doctors d
JOIN Departments dep ON d.DepartmentID = dep.DepartmentID;
GO