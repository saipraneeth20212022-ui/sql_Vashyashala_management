-- ?????????????????????????????????????????????
-- INNER JOIN: Patients who have been admitted with billing
-- ?????????????????????????????????????????????
SELECT 
    p.PatientID,
    CONCAT(p.FirstName,' ',p.LastName) AS Patient,
    a.Diagnosis,
    a.AdmissionDate,
    b.TotalAmount,
    b.PaymentStatus
FROM Patients p
INNER JOIN Admissions a ON p.PatientID  = a.PatientID
INNER JOIN Billing    b ON a.AdmissionID = b.AdmissionID
ORDER BY a.AdmissionDate DESC;

-- ?????????????????????????????????????????????
-- LEFT JOIN: ALL patients, even those never admitted
-- ?????????????????????????????????????????????
SELECT 
    p.PatientID,
    CONCAT(p.FirstName,' ',p.LastName)  AS Patient,
    p.RegisteredOn,
    ISNULL(CAST(a.AdmissionID AS VARCHAR), 'Never Admitted') AS AdmissionStatus
FROM Patients p
LEFT JOIN Admissions a ON p.PatientID = a.PatientID;

-- ?????????????????????????????????????????????
-- LEFT JOIN: Doctors who have NO admissions yet
-- (New doctors or specialties with no patients)
-- ?????????????????????????????????????????????
SELECT 
    d.DoctorID,
    CONCAT(d.FirstName,' ',d.LastName) AS Doctor,
    d.Specialization
FROM Doctors d
LEFT JOIN Admissions a ON d.DoctorID = a.DoctorID
WHERE a.AdmissionID IS NULL;

-- ?????????????????????????????????????????????
-- FULL OUTER JOIN: All departments vs all admissions
-- Catch departments with no patients AND admissions with no dept match
-- ?????????????????????????????????????????????
SELECT 
    ISNULL(dep.DeptName, 'Unknown Dept')         AS Department,
    ISNULL(CAST(a.AdmissionID AS VARCHAR), 'No Admissions') AS Admission
FROM Departments dep
FULL OUTER JOIN Admissions a ON dep.DepartmentID = a.DepartmentID;

-- ?????????????????????????????????????????????
-- SELF JOIN: Find patients readmitted within 30 days
-- ?????????????????????????????????????????????
SELECT
    a1.PatientID,
    CONCAT(p.FirstName,' ',p.LastName) AS Patient,
    a1.AdmissionID     AS FirstAdmission,
    a1.DischargeDate   AS DischargedOn,
    a2.AdmissionID     AS ReadmissionID,
    a2.AdmissionDate   AS ReadmittedOn,
    DATEDIFF(DAY, a1.DischargeDate, a2.AdmissionDate) AS DaysGap,
    a2.Diagnosis       AS ReadmissionDiagnosis
FROM Admissions a1
JOIN Admissions a2 
    ON  a1.PatientID  = a2.PatientID
    AND a2.AdmissionID > a1.AdmissionID
    AND a2.AdmissionDate >= a1.DischargeDate
    AND DATEDIFF(DAY, a1.DischargeDate, a2.AdmissionDate) <= 30
JOIN Patients p ON a1.PatientID = p.PatientID
WHERE a1.DischargeDate IS NOT NULL;

-- ?????????????????????????????????????????????
-- CROSS JOIN: All doctors × departments matrix
-- (Used for scheduling / coverage planning)
-- ?????????????????????????????????????????????
SELECT 
    CONCAT(d.FirstName,' ',d.LastName) AS Doctor,
    d.Specialization,
    dep.DeptName,
    CASE WHEN d.DepartmentID = dep.DepartmentID THEN '? Primary' ELSE '  Available' END AS Assignment
FROM Doctors d
CROSS JOIN Departments dep
ORDER BY d.LastName, dep.DeptName;

-- ?????????????????????????????????????????????
-- MULTI-TABLE JOIN: Complete patient journey
-- ?????????????????????????????????????????????
SELECT
    CONCAT(p.FirstName,' ',p.LastName) AS Patient,
    p.Age,
    p.BloodGroup,
    a.Diagnosis,
    a.AdmissionType,
    a.BedType,
    CONCAT(doc.FirstName,' ',doc.LastName) AS Doctor,
    dep.DeptName,
    lt.TestName,
    lt.IsAbnormal,
    b.TotalAmount,
    b.PaymentStatus
FROM Patients p
JOIN Admissions  a   ON p.PatientID    = a.PatientID
JOIN Doctors     doc ON a.DoctorID     = doc.DoctorID
JOIN Departments dep ON a.DepartmentID = dep.DepartmentID
LEFT JOIN LabTests lt ON a.AdmissionID  = lt.AdmissionID
LEFT JOIN Billing  b  ON a.AdmissionID  = b.AdmissionID
ORDER BY a.AdmissionDate;
GO