-- ?????????????????????????????????????????????
-- VIEW 1: Active admissions with full details
-- ?????????????????????????????????????????????
CREATE OR ALTER VIEW vw_ActiveAdmissions AS
SELECT
    a.AdmissionID,
    a.AdmissionDate,
    a.AdmissionType,
    a.Diagnosis,
    a.RoomNumber,
    a.BedType,
    CONCAT(p.FirstName, ' ', p.LastName) AS PatientName,
    p.Age,
    p.BloodGroup,
    CONCAT(d.FirstName, ' ', d.LastName) AS DoctorName,
    d.Specialization,
    dep.DeptName,
    DATEDIFF(DAY, a.AdmissionDate, GETDATE()) AS DaysAdmitted
FROM Admissions a
JOIN Patients   p   ON a.PatientID    = p.PatientID
JOIN Doctors    d   ON a.DoctorID     = d.DoctorID
JOIN Departments dep ON a.DepartmentID = dep.DepartmentID
WHERE a.Status = 'Active';
GO

-- ?????????????????????????????????????????????
-- VIEW 2: Patient billing summary
-- ?????????????????????????????????????????????
CREATE OR ALTER VIEW vw_BillingSummary AS
SELECT
    b.BillID,
    CONCAT(p.FirstName, ' ', p.LastName) AS PatientName,
    p.InsuranceID,
    a.Diagnosis,
    a.AdmissionDate,
    a.DischargeDate,
    b.RoomCharges,
    b.MedicineCharges,
    b.DoctorFee,
    b.LabCharges,
    b.TotalAmount,
    b.InsuranceCovered,
    b.AmountDue,
    b.PaymentStatus,
    CONCAT(d.FirstName, ' ', d.LastName) AS AttendingDoctor,
    dep.DeptName
FROM Billing b
JOIN Admissions  a   ON b.AdmissionID  = a.AdmissionID
JOIN Patients    p   ON b.PatientID    = p.PatientID
JOIN Doctors     d   ON a.DoctorID     = d.DoctorID
JOIN Departments dep ON a.DepartmentID = dep.DepartmentID;
GO

-- ?????????????????????????????????????????????
-- VIEW 3: Doctor workload summary
-- ?????????????????????????????????????????????
CREATE OR ALTER VIEW vw_DoctorWorkload AS
SELECT
    d.DoctorID,
    CONCAT(d.FirstName, ' ', d.LastName) AS DoctorName,
    d.Specialization,
    dep.DeptName,
    COUNT(a.AdmissionID)                          AS TotalPatients,
    SUM(CASE WHEN a.Status = 'Active' THEN 1 ELSE 0 END) AS CurrentPatients,
    COUNT(DISTINCT MONTH(a.AdmissionDate))         AS ActiveMonths,
    AVG(DATEDIFF(DAY, a.AdmissionDate, ISNULL(a.DischargeDate, GETDATE()))) AS AvgLOS
FROM Doctors d
LEFT JOIN Admissions  a   ON d.DoctorID     = a.DoctorID
LEFT JOIN Departments dep ON d.DepartmentID = dep.DepartmentID
GROUP BY d.DoctorID, d.FirstName, d.LastName, d.Specialization, dep.DeptName;
GO

-- ?????????????????????????????????????????????
-- VIEW 4: Department bed utilization
-- ?????????????????????????????????????????????
CREATE OR ALTER VIEW vw_BedUtilization AS
SELECT
    dep.DepartmentID,
    dep.DeptName,
    dep.MaxBeds,
    COUNT(a.AdmissionID) AS OccupiedBeds,
    dep.MaxBeds - COUNT(a.AdmissionID) AS AvailableBeds,
    CASE 
        WHEN dep.MaxBeds = 0 THEN 0
        ELSE CAST(COUNT(a.AdmissionID) * 100.0 / dep.MaxBeds AS DECIMAL(5,2))
    END AS OccupancyPct
FROM Departments dep
LEFT JOIN Admissions a ON dep.DepartmentID = a.DepartmentID AND a.Status = 'Active'
GROUP BY dep.DepartmentID, dep.DeptName, dep.MaxBeds;
GO

