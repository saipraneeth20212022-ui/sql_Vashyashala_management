-- PURPOSE: Real-world data cleaning pipeline
-- Covers: deduplication, standardization, null handling,
--         format correction, validation flags
-- ============================================================

USE HospitalDB;
GO

-- ?????????????????????????????????????????????
-- STEP 1: Standardize department names (fix casing)
-- ?????????????????????????????????????????????
UPDATE Departments
SET DeptName = UPPER(LEFT(LTRIM(RTRIM(DeptName)), 1)) 
             + LOWER(SUBSTRING(LTRIM(RTRIM(DeptName)), 2, LEN(DeptName)))
WHERE DeptName <> LTRIM(RTRIM(DeptName)) 
   OR DeptName LIKE '%[A-Z][A-Z]%';  -- catches ALL CAPS

-- Fix specific known bad values
UPDATE Departments SET DeptName = 'Oncology'    WHERE LOWER(DeptName) = 'oncology';
UPDATE Departments SET DeptName = 'Orthopedics' WHERE UPPER(DeptName) = 'ORTHOPEDICS';
UPDATE Departments
SET DeptHead = UPPER(LEFT(LTRIM(RTRIM(DeptHead)),1)) 
             + LOWER(SUBSTRING(LTRIM(RTRIM(DeptHead)),2,LEN(DeptHead)))
WHERE DeptHead IS NOT NULL;

-- ?????????????????????????????????????????????
-- STEP 2: Standardize patient names
-- ?????????????????????????????????????????????
UPDATE Patients
SET FirstName = UPPER(LEFT(LTRIM(RTRIM(FirstName)),1)) 
              + LOWER(SUBSTRING(LTRIM(RTRIM(FirstName)),2,LEN(FirstName))),
    LastName  = UPPER(LEFT(LTRIM(RTRIM(LastName)),1))  
              + LOWER(SUBSTRING(LTRIM(RTRIM(LastName)),2,LEN(LastName))),
    City      = UPPER(LEFT(LTRIM(RTRIM(City)),1))      
              + LOWER(SUBSTRING(LTRIM(RTRIM(City)),2,LEN(City)));

-- ?????????????????????????????????????????????
-- STEP 3: Fix invalid gender codes
-- ?????????????????????????????????????????????
UPDATE Patients
SET Gender = 'O'   -- Other / Unknown
WHERE Gender NOT IN ('M','F','O') OR Gender IS NULL;

-- ?????????????????????????????????????????????
-- STEP 4: Clean doctor phone numbers
-- Remove non-numeric characters except + for country code
-- ?????????????????????????????????????????????
UPDATE Doctors
SET Phone = NULL
WHERE Phone IN ('N/A', 'n/a', 'NA', '-', '') 
   OR Phone NOT LIKE '%[0-9]%';

-- Strip dashes and spaces from phones
UPDATE Doctors
SET Phone = REPLACE(REPLACE(REPLACE(REPLACE(Phone,' ',''),'-',''),'(',''),')','')
WHERE Phone IS NOT NULL;

-- ?????????????????????????????????????????????
-- STEP 5: Handle NULL billing room charges
-- ?????????????????????????????????????????????
UPDATE Billing
SET RoomCharges = 0
WHERE RoomCharges IS NULL;

-- ?????????????????????????????????????????????
-- STEP 6: Remove duplicate patients
-- Keep the row with the lowest PatientID (first registered)
-- ?????????????????????????????????????????????
-- First, see what duplicates exist
SELECT 
    Phone,
    DOB,
    COUNT(*) AS DuplicateCount,
    MIN(PatientID) AS KeepID,
    MAX(PatientID) AS DeleteID
FROM Patients
GROUP BY Phone, DOB
HAVING COUNT(*) > 1;

-- Remove duplicates (keep lowest ID)
DELETE FROM Patients
WHERE PatientID NOT IN (
    SELECT MIN(PatientID)
    FROM Patients
    GROUP BY LOWER(FirstName), LOWER(LastName), DOB, Phone
);

-- ?????????????????????????????????????????????
-- STEP 7: Add a data quality flag column and tag issues
-- ?????????????????????????????????????????????
ALTER TABLE Patients ADD DataQualityFlag VARCHAR(200) NULL;

UPDATE Patients
SET DataQualityFlag = CONCAT(
    CASE WHEN Phone IS NULL             THEN 'MISSING_PHONE; '    ELSE '' END,
    CASE WHEN Email IS NULL             THEN 'MISSING_EMAIL; '    ELSE '' END,
    CASE WHEN InsuranceID IS NULL       THEN 'NO_INSURANCE; '     ELSE '' END,
    CASE WHEN BloodGroup IS NULL        THEN 'NO_BLOODGROUP; '    ELSE '' END,
    CASE WHEN DATEDIFF(YEAR,DOB,GETDATE()) > 100 THEN 'CHECK_DOB; ' ELSE '' END
);

UPDATE Patients SET DataQualityFlag = NULL WHERE DataQualityFlag = '';

-- ?????????????????????????????????????????????
-- STEP 8: Calculate and store patient age
-- ?????????????????????????????????????????????
ALTER TABLE Patients ADD Age INT NULL;

UPDATE Patients
SET Age = DATEDIFF(YEAR, DOB, GETDATE())
        - CASE WHEN MONTH(DOB) > MONTH(GETDATE()) 
               OR (MONTH(DOB) = MONTH(GETDATE()) AND DAY(DOB) > DAY(GETDATE()))
               THEN 1 ELSE 0 END;

-- ?????????????????????????????????????????????
-- STEP 9: Standardize AdmissionType values
-- ?????????????????????????????????????????????
UPDATE Admissions
SET AdmissionType = 
    CASE 
        WHEN LOWER(AdmissionType) LIKE '%emerg%' THEN 'Emergency'
        WHEN LOWER(AdmissionType) LIKE '%elect%' THEN 'Elective'
        WHEN LOWER(AdmissionType) LIKE '%transf%' THEN 'Transfer'
        ELSE 'Unknown'
    END;

-- ?????????????????????????????????????????????
-- STEP 10: Validation report after cleaning
-- ?????????????????????????????????????????????
SELECT 'Patients with flags'       AS CheckName, COUNT(*) AS Count FROM Patients WHERE DataQualityFlag IS NOT NULL
UNION ALL
SELECT 'Doctors with NULL phone',             COUNT(*) FROM Doctors WHERE Phone IS NULL
UNION ALL
SELECT 'Admissions with no discharge',        COUNT(*) FROM Admissions WHERE DischargeDate IS NULL
UNION ALL
SELECT 'Bills with Pending payment',          COUNT(*) FROM Billing WHERE PaymentStatus = 'Pending'
UNION ALL
SELECT 'Abnormal lab results',                COUNT(*) FROM LabTests WHERE IsAbnormal = 1;

PRINT 'Data cleaning complete.';
GO