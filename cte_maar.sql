-- ?????????????????????????????????????????????
-- CTE 1: Average length of stay per department
-- ?????????????????????????????????????????????
WITH DeptLOS AS (
    SELECT
        dep.DeptName,
        a.AdmissionID,
        a.AdmissionDate,
        ISNULL(a.DischargeDate, GETDATE()) AS EffectiveDischarge,
        DATEDIFF(DAY, a.AdmissionDate, ISNULL(a.DischargeDate, GETDATE())) AS LOS
    FROM Admissions a
    JOIN Departments dep ON a.DepartmentID = dep.DepartmentID
)
SELECT
    DeptName,
    COUNT(*)          AS TotalAdmissions,
    AVG(LOS)          AS AvgLOS_Days,
    MIN(LOS)          AS MinLOS,
    MAX(LOS)          AS MaxLOS
FROM DeptLOS
GROUP BY DeptName
ORDER BY AvgLOS_Days DESC;
GO

-- ?????????????????????????????????????????????
-- CTE 2: Top spending patients (chained CTEs)
-- ?????????????????????????????????????????????
WITH PatientSpend AS (
    SELECT
        b.PatientID,
        SUM(b.TotalAmount)      AS TotalBilled,
        SUM(b.InsuranceCovered) AS TotalInsurance,
        SUM(b.AmountDue)        AS TotalOutOfPocket
    FROM Billing b
    GROUP BY b.PatientID
),
RankedPatients AS (
    SELECT
        ps.PatientID,
        CONCAT(p.FirstName,' ',p.LastName) AS PatientName,
        ps.TotalBilled,
        ps.TotalInsurance,
        ps.TotalOutOfPocket,
        RANK() OVER (ORDER BY ps.TotalBilled DESC) AS SpendRank
    FROM PatientSpend ps
    JOIN Patients p ON ps.PatientID = p.PatientID
)
SELECT * FROM RankedPatients
ORDER BY SpendRank;
GO

-- ?????????????????????????????????????????????
-- CTE 3: Recursive CTE — Generate a date series
-- Used for: filling gaps in daily admission counts
-- ?????????????????????????????????????????????
WITH DateSeries AS (
    SELECT CAST('2024-01-01' AS DATE) AS ReportDate
    UNION ALL
    SELECT DATEADD(DAY, 1, ReportDate)
    FROM DateSeries
    WHERE ReportDate < '2024-03-31'
)
SELECT
    ds.ReportDate,
    ISNULL(COUNT(a.AdmissionID), 0) AS DailyAdmissions
FROM DateSeries ds
LEFT JOIN Admissions a 
    ON CAST(a.AdmissionDate AS DATE) = ds.ReportDate
GROUP BY ds.ReportDate
ORDER BY ds.ReportDate
OPTION (MAXRECURSION 365);
GO

-- ?????????????????????????????????????????????
-- CTE 4: Identify abnormal test patients
-- and cross-reference with billing
-- ?????????????????????????????????????????????
WITH AbnormalCases AS (
    SELECT DISTINCT
        lt.AdmissionID,
        COUNT(lt.TestID) AS AbnormalTestCount
    FROM LabTests lt
    WHERE lt.IsAbnormal = 1
    GROUP BY lt.AdmissionID
),
HighRiskAdmissions AS (
    SELECT
        ac.AdmissionID,
        ac.AbnormalTestCount,
        a.PatientID,
        a.Diagnosis,
        a.BedType
    FROM AbnormalCases ac
    JOIN Admissions a ON ac.AdmissionID = a.AdmissionID
    WHERE ac.AbnormalTestCount >= 2
)
SELECT
    hra.AdmissionID,
    CONCAT(p.FirstName,' ',p.LastName) AS Patient,
    hra.Diagnosis,
    hra.BedType,
    hra.AbnormalTestCount,
    ISNULL(b.TotalAmount, 0) AS TotalBill
FROM HighRiskAdmissions hra
JOIN Patients p ON hra.PatientID = p.PatientID
LEFT JOIN Billing b ON hra.AdmissionID = b.AdmissionID;
GO

-- ?????????????????????????????????????????????
-- CORRELATED SUBQUERY: Patients whose bill is above 
-- their department's average bill
-- ?????????????????????????????????????????????
SELECT
    CONCAT(p.FirstName,' ',p.LastName) AS Patient,
    dep.DeptName,
    b.TotalAmount AS PatientBill,
    (
        SELECT AVG(b2.TotalAmount)
        FROM Billing b2
        JOIN Admissions a2 ON b2.AdmissionID = a2.AdmissionID
        WHERE a2.DepartmentID = a.DepartmentID
    ) AS DeptAvgBill
FROM Billing b
JOIN Admissions  a   ON b.AdmissionID  = a.AdmissionID
JOIN Patients    p   ON b.PatientID    = p.PatientID
JOIN Departments dep ON a.DepartmentID = dep.DepartmentID
WHERE b.TotalAmount > (
    SELECT AVG(b2.TotalAmount)
    FROM Billing b2
    JOIN Admissions a2 ON b2.AdmissionID = a2.AdmissionID
    WHERE a2.DepartmentID = a.DepartmentID
);
GO