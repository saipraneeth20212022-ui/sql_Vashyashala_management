USE master;
GO

IF EXISTS (SELECT name FROM sys.databases WHERE name = 'HospitalDB')
    DROP DATABASE HospitalDB;
GO

CREATE DATABASE HospitalDB;
GO

USE HospitalDB;
GO

-- ?????????????????????????????????????????????
-- DEPARTMENTS
-- ?????????????????????????????????????????????
CREATE TABLE Departments (
    DepartmentID   INT PRIMARY KEY IDENTITY(1,1),
    DeptName       VARCHAR(100) NOT NULL,
    DeptHead       VARCHAR(100),
    Floor          INT,
    MaxBeds        INT DEFAULT 0,
    CreatedAt      DATETIME DEFAULT GETDATE()
);

-- ?????????????????????????????????????????????
-- DOCTORS
-- ?????????????????????????????????????????????
CREATE TABLE Doctors (
    DoctorID       INT PRIMARY KEY IDENTITY(1,1),
    FirstName      VARCHAR(50) NOT NULL,
    LastName        VARCHAR(50) NOT NULL,
    Specialization VARCHAR(100),
    DepartmentID   INT FOREIGN KEY REFERENCES Departments(DepartmentID),
    Phone          VARCHAR(20),
    Email          VARCHAR(100),
    HireDate       DATE,
    Salary         DECIMAL(10,2),
    IsActive       BIT DEFAULT 1
);

-- ?????????????????????????????????????????????
-- PATIENTS
-- ?????????????????????????????????????????????
CREATE TABLE Patients (
    PatientID      INT PRIMARY KEY IDENTITY(1,1),
    FirstName      VARCHAR(50),
    LastName        VARCHAR(50),
    DOB            DATE,
    Gender         CHAR(1),          -- M / F / O
    BloodGroup     VARCHAR(5),
    Phone          VARCHAR(20),
    Email          VARCHAR(100),
    Address        VARCHAR(255),
    City           VARCHAR(50),
    InsuranceID    VARCHAR(50),
    RegisteredOn   DATETIME DEFAULT GETDATE()
);

-- ?????????????????????????????????????????????
-- ADMISSIONS
-- ?????????????????????????????????????????????
CREATE TABLE Admissions (
    AdmissionID    INT PRIMARY KEY IDENTITY(1,1),
    PatientID      INT FOREIGN KEY REFERENCES Patients(PatientID),
    DoctorID       INT FOREIGN KEY REFERENCES Doctors(DoctorID),
    DepartmentID   INT FOREIGN KEY REFERENCES Departments(DepartmentID),
    AdmissionDate  DATETIME NOT NULL,
    DischargeDate  DATETIME NULL,
    AdmissionType  VARCHAR(20),      -- Emergency / Elective / Transfer
    Diagnosis      VARCHAR(255),
    RoomNumber     VARCHAR(10),
    BedType        VARCHAR(20),      -- General / ICU / Private
    Status         VARCHAR(20) DEFAULT 'Active'  -- Active / Discharged / Transferred
);

-- ?????????????????????????????????????????????
-- BILLING
-- ?????????????????????????????????????????????
CREATE TABLE Billing (
    BillID         INT PRIMARY KEY IDENTITY(1,1),
    AdmissionID    INT FOREIGN KEY REFERENCES Admissions(AdmissionID),
    PatientID      INT FOREIGN KEY REFERENCES Patients(PatientID),
    RoomCharges    DECIMAL(10,2) DEFAULT 0,
    MedicineCharges DECIMAL(10,2) DEFAULT 0,
    DoctorFee      DECIMAL(10,2) DEFAULT 0,
    LabCharges     DECIMAL(10,2) DEFAULT 0,
    TotalAmount    AS (RoomCharges + MedicineCharges + DoctorFee + LabCharges),  -- computed column
    InsuranceCovered DECIMAL(10,2) DEFAULT 0,
    AmountDue      AS (RoomCharges + MedicineCharges + DoctorFee + LabCharges - InsuranceCovered),
    PaymentStatus  VARCHAR(20) DEFAULT 'Pending',   -- Pending / Paid / Partial
    BillDate       DATETIME DEFAULT GETDATE()
);

-- ?????????????????????????????????????????????
-- LAB TESTS
-- ?????????????????????????????????????????????
CREATE TABLE LabTests (
    TestID         INT PRIMARY KEY IDENTITY(1,1),
    AdmissionID    INT FOREIGN KEY REFERENCES Admissions(AdmissionID),
    TestName       VARCHAR(100),
    OrderedBy      INT FOREIGN KEY REFERENCES Doctors(DoctorID),
    TestDate       DATETIME DEFAULT GETDATE(),
    Result         VARCHAR(255),
    IsAbnormal     BIT DEFAULT 0,
    Cost           DECIMAL(8,2)
);

-- ?????????????????????????????????????????????
-- MEDICATIONS
-- ?????????????????????????????????????????????
CREATE TABLE Medications (
    MedID          INT PRIMARY KEY IDENTITY(1,1),
    AdmissionID    INT FOREIGN KEY REFERENCES Admissions(AdmissionID),
    MedName        VARCHAR(100),
    Dosage         VARCHAR(50),
    PrescribedBy   INT FOREIGN KEY REFERENCES Doctors(DoctorID),
    StartDate      DATE,
    EndDate        DATE,
    Cost           DECIMAL(8,2)
);

-- ?????????????????????????????????????????????
-- AUDIT LOG (used by triggers)
-- ?????????????????????????????????????????????
CREATE TABLE AuditLog (
    LogID          INT PRIMARY KEY IDENTITY(1,1),
    TableName      VARCHAR(50),
    ActionType     VARCHAR(10),      -- INSERT / UPDATE / DELETE
    RecordID       INT,
    ChangedBy      VARCHAR(100) DEFAULT SYSTEM_USER,
    ChangedAt      DATETIME DEFAULT GETDATE(),
    OldValues      NVARCHAR(MAX),
    NewValues      NVARCHAR(MAX)
);

PRINT 'Schema created successfully.';
GO